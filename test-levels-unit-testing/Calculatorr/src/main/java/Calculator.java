public class Calculator {
    public double add(double summand1, double summand2) {
        return summand1 + summand2;
    }

    public double subtract(double summand1, double summand2) {
        return summand1 - summand2;
    }

    public double multiply(double summand1, double summand2) {
        return summand1 * summand2;
    }

    public double divide(double summand1, double summand2) {
        return summand1 / summand2;
    }
}
